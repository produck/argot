export const BYTE = 1;

export const STEP = 1 << 10;

export const KILO_BYTE = STEP * BYTE;

export const MEGA_BYTE = STEP * KILO_BYTE;

export const GIGA_BYTE = STEP * MEGA_BYTE;

export const TERA_BYTE = STEP * GIGA_BYTE;

export {
  BYTE as B,
  KILO_BYTE as KB,
  MEGA_BYTE as MB,
  GIGA_BYTE as GB,
  TERA_BYTE as TB,
};
